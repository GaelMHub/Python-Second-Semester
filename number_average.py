# Reads three numbers from the user and prints their average.

print("Enter your first number:")
num1 = float(input())
print("Enter your second number:")
num2 = float(input())
print("Enter your third number:")
num3 = float(input())
average = (num1 + num2 + num3) / 3
print("The average is:", average)
